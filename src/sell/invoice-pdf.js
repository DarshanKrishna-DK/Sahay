"use strict";

/**
 * The invoice PDF (tax invoice, bill of supply or plain bill) of an issued invoice. `invoiceModel`
 * decides every word on the page from the stored invoice (its supplier/recipient snapshots taken
 * at issue); `writeInvoicePdf` draws it with PDFKit and stores the path on the invoice.
 * Text in Devanagari or Kannada is drawn with the bundled Noto fonts through the same font runs
 * as the purchase order (src/orders/po.js fontRuns); text no font can print refuses the PDF.
 *
 * Fields follow CGST Rules 46 (tax invoice) and 49 (bill of supply) as listed on
 * cbic-gst.gov.in/gst-invoice-rules.html: supplier name, address, GSTIN; serial number; date;
 * recipient name, address, GSTIN; HSN; description; quantity and unit; value; taxable value;
 * rate and amount of CGST + SGST or IGST; place of supply with state; reverse charge; signature.
 */

const fs = require("node:fs");
const path = require("node:path");
const PDFDocument = require("pdfkit");
const db = require("../db");
const { config } = require("../config");
const { fontRuns } = require("../orders/po");
const gst = require("./gst");
const gate = require("./gate");
const { SellError } = require("./errors");

const INK = "#14140f";
const MUTED = "#6b6558";
const ACCENT = "#1f6f5c";
const RULE = "#ddd6c6";
const MARGIN = 40;

const money = (paise) => `Rs. ${(paise / 100).toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
const qty = (n) => Number(n).toLocaleString("en-IN", { maximumFractionDigits: 3 });
const dateInIndia = (iso) => new Date(iso).toLocaleDateString("en-IN", { timeZone: "Asia/Kolkata", day: "2-digit", month: "short", year: "numeric" });
const present = (list) => list.filter(Boolean);
const stateLine = (code, name) => (code ? `State: ${name ?? gst.stateName(code) ?? ""} (code ${code})` : null);

/** Words a composition dealer prints on a bill of supply (CGST Rule 5(1)(g)). */
const COMPOSITION_NOTE = "Composition taxable person, not eligible to collect tax on supplies.";
const FOOTER = "Generated by Sahay, an automated billing assistant. Check GST details with your CA.";

/** Everything the invoice says, as plain data. */
function invoiceModel(invoice, approval) {
  const s = invoice.supplier;
  const r = invoice.recipient;
  const taxed = invoice.kind === "tax_invoice";
  const columns = taxed ? (invoice.intraState ? ["cgst", "sgst"] : ["igst"]) : [];
  return {
    title: gst.KIND_TITLE[invoice.kind].toUpperCase(),
    number: invoice.number,
    date: dateInIndia(invoice.issuedAt),
    note: invoice.kind === "bill_of_supply" ? COMPOSITION_NOTE : null,
    supplier: { name: s.name, lines: present([s.address, s.gstin ? `GSTIN: ${s.gstin}` : "Not registered under GST", stateLine(s.stateCode, s.stateName)]) },
    recipient: {
      name: r.name,
      lines: present([r.address, r.gstin ? `GSTIN: ${r.gstin}` : "Unregistered", stateLine(r.stateCode, r.stateName), r.phone ? `Phone: ${r.phone}` : null]),
    },
    facts: present([
      `Place of supply: ${invoice.placeOfSupply.name} (code ${invoice.placeOfSupply.code})`,
      taxed ? `Supply: ${invoice.intraState ? "intra-state (CGST + SGST)" : "inter-state (IGST)"}` : null,
      "Tax payable on reverse charge: No",
    ]),
    taxColumns: columns,
    lines: invoice.lines.map((l, i) => ({
      no: String(i + 1),
      description: l.name,
      hsn: l.hsn ?? "",
      quantity: `${qty(l.quantity)} ${l.unit}`,
      rate: money(l.ratePaise),
      taxable: money(l.taxablePaise),
      cgst: taxed && invoice.intraState ? `${l.gstRate / 2}%  ${money(l.cgstPaise)}` : "",
      sgst: taxed && invoice.intraState ? `${l.gstRate / 2}%  ${money(l.sgstPaise)}` : "",
      igst: taxed && !invoice.intraState ? `${l.gstRate}%  ${money(l.igstPaise)}` : "",
    })),
    totals: present([
      ["Taxable value", money(invoice.totals.taxablePaise)],
      taxed && invoice.intraState && ["CGST", money(invoice.totals.cgstPaise)],
      taxed && invoice.intraState && ["SGST", money(invoice.totals.sgstPaise)],
      taxed && !invoice.intraState && ["IGST", money(invoice.totals.igstPaise)],
    ]),
    total: money(invoice.totals.totalPaise),
    words: gst.rupeesInWords(invoice.totals.totalPaise),
    signature: `For ${s.name}`,
    approval: `Issued on the owner's ${approval.decided_via === "voice" ? "spoken" : "on-screen"} confirmation on ${dateInIndia(approval.decided_at)} (approval ${approval.id}).`,
    footer: FOOTER,
  };
}

/** Refuse before a file is opened if any text on the page has no font that can print it. */
function assertPrintable(value) {
  if (typeof value === "string") fontRuns(value);
  else if (value && typeof value === "object") Object.values(value).forEach(assertPrintable);
}

function draw(doc, model) {
  const width = doc.page.width - MARGIN * 2;
  const half = width / 2;
  const registered = new Set();
  const put = (text, { size, color = INK, bold = false, x, y, ...options } = {}) => {
    const runs = fontRuns(text);
    doc.fontSize(size).fillColor(color);
    runs.forEach((run, i) => {
      if (run.font === "Helvetica") doc.font(bold ? "Helvetica-Bold" : "Helvetica");
      else {
        if (!registered.has(run.font.script)) {
          doc.registerFont(run.font.script, ...run.font.source);
          registered.add(run.font.script);
        }
        doc.font(run.font.script);
      }
      const runOptions = { ...options, continued: i < runs.length - 1 };
      if (i === 0 && x !== undefined) doc.text(run.text, x, y, runOptions);
      else doc.text(run.text, runOptions);
    });
  };

  put(model.title, { size: 10, color: ACCENT, characterSpacing: 3 });
  put(model.number, { size: 20, bold: true });
  put(`Date ${model.date}`, { size: 9.5, color: MUTED });
  if (model.note) put(model.note, { size: 9.5, bold: true });
  doc.moveDown(0.8);

  const top = doc.y;
  const party = (label, { name, lines }, x) => {
    put(label, { size: 8.5, color: MUTED, x, y: top, width: half - 12 });
    put(name, { size: 11, bold: true, x, y: doc.y + 2, width: half - 12 });
    for (const line of lines) put(line, { size: 9, color: MUTED, x, y: doc.y + 1, width: half - 12 });
    return doc.y;
  };
  let y = Math.max(party("SUPPLIER", model.supplier, MARGIN), party("BILL TO", model.recipient, MARGIN + half)) + 10;
  for (const fact of model.facts) {
    put(fact, { size: 9, x: MARGIN, y, width });
    y = doc.y + 1;
  }
  y += 8;
  const rule = () => doc.moveTo(MARGIN, y).lineTo(doc.page.width - MARGIN, y).strokeColor(RULE).lineWidth(1).stroke();
  rule();
  y += 8;

  // # | description | HSN | qty | rate | taxable | tax columns
  const taxCols = model.taxColumns.length;
  const fixed = { no: 18, hsn: 50, quantity: 60, rate: 66, taxable: 72 };
  const taxWidth = taxCols ? 92 : 0;
  const descWidth = width - Object.values(fixed).reduce((a, b) => a + b, 0) - taxWidth * taxCols;
  const order = ["no", "description", "hsn", "quantity", "rate", "taxable", ...model.taxColumns];
  const widths = { ...fixed, description: descWidth, cgst: taxWidth, sgst: taxWidth, igst: taxWidth };
  const heads = { no: "#", description: "DESCRIPTION", hsn: "HSN", quantity: "QTY", rate: "RATE", taxable: "TAXABLE", cgst: "CGST", sgst: "SGST", igst: "IGST" };
  const xs = {};
  order.reduce((x, key) => ((xs[key] = x), x + widths[key]), MARGIN);
  const row = (cells, options) => {
    let bottom = y;
    for (const key of order) {
      put(cells[key] ?? "", { x: xs[key], y, width: widths[key] - 4, align: key === "description" || key === "no" ? "left" : "right", ...options });
      bottom = Math.max(bottom, doc.y);
    }
    y = bottom + 6;
  };
  row(heads, { size: 8, color: MUTED });
  for (const line of model.lines) row(line, { size: 9 });
  rule();
  y += 8;

  const labelX = MARGIN + width - 260;
  const summary = (label, value, options) => {
    put(label, { x: labelX, y, width: 140, align: "right", ...options });
    const labelBottom = doc.y;
    put(value, { x: labelX + 150, y, width: 110, align: "right", ...options });
    y = Math.max(labelBottom, doc.y) + 5;
  };
  for (const [label, value] of model.totals) summary(label, value, { size: 9.5, color: MUTED });
  summary("Total", model.total, { size: 13, bold: true });
  put(`Amount in words: ${model.words}`, { size: 9, x: MARGIN, y: y + 6, width });

  doc.moveDown(2.5);
  put(model.signature, { size: 10, bold: true, x: MARGIN + width - 200, y: doc.y, width: 200, align: "right" });
  put("Authorised signatory", { size: 8.5, color: MUTED, x: MARGIN + width - 200, y: doc.y + 18, width: 200, align: "right" });
  doc.moveDown(2);
  put(model.approval, { size: 8, color: MUTED, x: MARGIN, y: doc.y, width });
  put(model.footer, { size: 8, color: MUTED, x: MARGIN, y: doc.y + 2, width });
}

const invoicesDir = () => path.join(path.dirname(config.poDir), "invoices");

function pdfFilePath(invoiceId) {
  if (!/^inv_[0-9a-f]{20}$/.test(invoiceId)) throw new SellError("INVALID", "That is not an invoice id.");
  return path.join(invoicesDir(), `${invoiceId}.pdf`);
}

/** Draw the PDF of an issued invoice, store its path on the invoice and return the path. */
async function writeInvoicePdf(businessId, invoiceId) {
  const invoice = gate.assertIssued(businessId, invoiceId);
  const approval = gate.approvalRow(businessId, invoice.approvalId);
  const model = invoiceModel(invoice, approval);
  assertPrintable(model);
  const file = pdfFilePath(invoice.id);
  const partial = `${file}.${process.pid}.part`;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  await new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: MARGIN, info: { Title: `${gst.KIND_TITLE[invoice.kind]} ${invoice.number}`, Author: invoice.supplier.name, Creator: "Sahay" } });
    const out = fs.createWriteStream(partial);
    const fail = (err) => {
      out.destroy();
      fs.rmSync(partial, { force: true });
      reject(err);
    };
    out.on("error", fail);
    out.on("finish", () => {
      try {
        fs.renameSync(partial, file);
        resolve();
      } catch (err) {
        fail(err);
      }
    });
    doc.on("error", fail);
    doc.pipe(out);
    try {
      draw(doc, model);
      doc.end();
    } catch (err) {
      doc.unpipe(out);
      fail(err);
    }
  });
  db.prepare("UPDATE invoices SET pdf_path = ? WHERE business_id = ? AND id = ?").run(file, businessId, invoice.id);
  return file;
}

/** The stored PDF of an issued invoice of this business; writes it when it is missing. */
async function pdfPathFor(businessId, invoiceId) {
  const invoice = gate.assertIssued(businessId, invoiceId);
  if (invoice.pdfPath && fs.existsSync(invoice.pdfPath)) return invoice.pdfPath;
  return writeInvoicePdf(businessId, invoice.id);
}

module.exports = { invoiceModel, writeInvoicePdf, pdfPathFor, pdfFilePath, COMPOSITION_NOTE };
