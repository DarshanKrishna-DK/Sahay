// Shared helpers for the landing-page figure builds (node scripts/figures/build.mjs).
// The anatomy kit (MIT, see kit/LICENSE) is copied into public/figures/ so the live figures can
// project and rebuild the few parts that move; everything static is precomputed here.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const HERE = dirname(fileURLToPath(import.meta.url));
export const ROOT = join(HERE, "..", "..");
export const OUT = join(ROOT, "public", "figures");

/** public/figures/*.js are browser ES modules in a CommonJS package: load one as data. */
export async function importBrowserModule(name) {
  const source = readFileSync(join(OUT, name), "utf8");
  return import(`data:text/javascript,${encodeURIComponent(source)}`);
}

export function writeOut(name, text) {
  mkdirSync(OUT, { recursive: true });
  writeFileSync(join(OUT, name), text);
  console.log("wrote", `public/figures/${name}`, `(${(Buffer.byteLength(text) / 1024).toFixed(1)} KB)`);
}

/** The kit's core, as a browser module beside the figures (same file, MIT header kept). */
export function copyKit() {
  const kit = readFileSync(join(HERE, "kit", "iso-kit.mjs"), "utf8");
  const header = "// Anatomy iso kit (MIT License, Copyright (c) 2026 Ryan; full text in scripts/figures/kit/LICENSE).\n// Generated copy: edit scripts/figures/kit/iso-kit.mjs and run node scripts/figures/build.mjs.\n";
  writeOut("iso-kit.js", header + kit);
  copyFileSync(join(HERE, "kit", "LICENSE"), join(OUT, "LICENSE-anatomy.txt"));
}

/** A generated ES module holding the numbers the live code needs (camera, anchors). */
export function geoModule(name, data) {
  writeOut(name, `// Generated by scripts/figures/build.mjs. Do not edit.\nexport const GEO = ${JSON.stringify(data)};\n`);
}

/** Static SVG fragment: tokens come from public/figures/figures.css on the host page. */
export function svgOf({ width, height, label, body, className }) {
  const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/"/g, "&quot;");
  return `<svg xmlns="http://www.w3.org/2000/svg" class="iso-svg ${className}" viewBox="0 0 ${width} ${height}" role="img" aria-label="${esc(label)}">${body.join("")}</svg>\n`;
}

/** A coil spring around a vertical axis, split into the half behind the rod and the half in front. */
export function coilZ(k, cx, cy, z0, z1, radius, turns, P, perTurn = 18) {
  const count = Math.max(1, Math.round(turns * perTurn));
  const back = [];
  const front = [];
  let run = [];
  let near = null;
  for (let i = 0; i <= count; i++) {
    const share = i / count;
    const angle = share * turns * Math.PI * 2;
    const point = [cx + radius * Math.cos(angle), cy + radius * Math.sin(angle), z0 + (z1 - z0) * share];
    const facing = k.depthOf([Math.cos(angle), Math.sin(angle), 0], P) > 0;
    const flat = k.iso(point, P);
    if (near === null) near = facing;
    if (facing !== near) {
      run.push(flat);
      (near ? front : back).push(k.pathOf(run));
      run = [flat];
      near = facing;
      continue;
    }
    run.push(flat);
  }
  if (run.length > 1) (near ? front : back).push(k.pathOf(run));
  return { back: back.join(""), front: front.join("") };
}
